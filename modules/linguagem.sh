linguagem_menu(){
    clear
    echo -e "${C_CYAN}== ${L_LANGUAGE} ==${C_NC}"
    echo
    echo "  1) Português (PT)"
    echo "  2) Español   (ES)"
    echo "  3) English   (EN)"
    echo
    read -rp " 选择 / Selecciona / Choose [1-3]: " opt
    local code
    case "$opt" in
        1) code="pt" ;;
        2) code="es" ;;
        3) code="en" ;;
        *) fail "${L_INVALID_OPT}"; sleep 1; return ;;
    esac
    _lang_set "$code"
    mkdir -p "$(dirname "$LANG_FILE")"
    echo "$code" > "$LANG_FILE"
    ok "Idioma / Language: $code"
    sleep 1
}
